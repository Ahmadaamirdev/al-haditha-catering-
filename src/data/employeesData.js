// Helper functions for matching
export function findEmployee(identifier) {
  if (!identifier) return null;
  const clean = identifier.toString().trim().toLowerCase();
  return alHadithaEmployees.find(
    (emp) =>
      emp.id.toLowerCase() === clean ||
      emp.name.toLowerCase() === clean
  );
}

export function matchEmployeeByIdAndName(idInput, nameInput) {
  const cleanId = (idInput || '').toString().trim().toUpperCase();
  const cleanName = (nameInput || '').toString().trim().toLowerCase();

  if (!cleanId) {
    return {
      matched: false,
      reason: 'MISSING_ID',
      message: 'Please enter your Employee ID.'
    };
  }

  if (!cleanName) {
    return {
      matched: false,
      reason: 'MISSING_NAME',
      message: 'Please enter your Full Name.'
    };
  }

  // 1. Find employee by ID
  const employeeById = alHadithaEmployees.find(
    (emp) => emp.id.toUpperCase() === cleanId
  );

  if (!employeeById) {
    return {
      matched: false,
      reason: 'ID_NOT_FOUND',
      message: `Employee ID "${cleanId}" not found in company records.`
    };
  }

  // 2. Verify Name against this employee record
  const empNameLower = employeeById.name.toLowerCase();

  // Helper to normalize name (strip titles and non-alphanumeric chars)
  const norm = (str) =>
    str
      .replace(/^(eng\.|dr\.|chef|sheikh)\s+/i, '')
      .replace(/[^a-z0-9]/g, '');

  const normEmpName = norm(empNameLower);
  const normInputName = norm(cleanName);

  const isMatched =
    empNameLower === cleanName ||
    empNameLower.includes(cleanName) ||
    cleanName.includes(empNameLower) ||
    normEmpName === normInputName ||
    normEmpName.includes(normInputName) ||
    normInputName.includes(normEmpName);

  if (!isMatched) {
    return {
      matched: false,
      reason: 'NAME_MISMATCH',
      expectedName: employeeById.name,
      message: `Verification Failed: The entered name does not match the record for ID "${cleanId}".`
    };
  }

  return {
    matched: true,
    approved: true,
    employee: employeeById,
    message: `APPROVED: Welcome, ${employeeById.name}!`
  };
}
